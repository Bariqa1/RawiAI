def build_corpus():
    processor = PoetryCorpusProcessor()
    records = []
    for idx, item in enumerate(RAW_POEMS):
        enriched = processor.process_verse_text(
            raw_text=item["text"],
            poet=item["poet"],
            era=item["era"],
            theme=item["theme"],
            poem_title=item["title"],
            source_row=idx
        )
        if enriched:
            records.append(enriched.model_dump())

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "classical_poetry_corpus.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)

    print(f"Generated {len(records)} enriched classical verses in: {out_path}")


if __name__ == "__main__":
    build_corpus()
